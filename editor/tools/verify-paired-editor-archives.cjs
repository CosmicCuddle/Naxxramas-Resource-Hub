'use strict';
/*
 * OFFLINE PAIR VALIDATION — no combined deployment package.
 *
 * Two independent review-only archives are accepted as a matched pair ONLY
 * when regenerated from the same exact v3 page draft, v2 resource draft,
 * pinned clean Git checkout and hash-only review receipt. Compare FULL ZIP
 * bytes against deterministic independently reconstructed canonical archives.
 *
 * Does not commit, publish, upload, replace files, mutate a checkout, or
 * establish owner approval. No archive contents or private file paths printed.
 */
const fs=require('node:fs'),path=require('node:path');
const crypto=require('node:crypto');
const {verifyReviewBinding}=require('./bind-editor-drafts.cjs');
const {sourceDraft}=require('./create-draft-review-receipt.cjs');
const {createPagePackage}=require('./package-reviewed-page-update.cjs');
const {createResourcePreview}=require('./package-reviewed-resource-preview.cjs');
const sha=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');

function checkArchive(value,label){
  if(!Buffer.isBuffer(value)||value.length<22||value.length>75*1024*1024)
    throw Error('Missing or oversized private '+label+' archive.');
}
async function verifyPairedArchives(root,drafts,receipt,pageZip,resourceZip){
  checkArchive(pageZip,'page');
  checkArchive(resourceZip,'resource');
  if(!drafts||!drafts.pages||!drafts.resources)
    throw Error('Both exact draft formats are required for paired review.');
  const binding=await verifyReviewBinding(root,drafts,receipt);
  if(binding.pageDraftMatchesReceipt!==true||
     binding.resourceDraftMatchesReceipt!==true||
     binding.existingPagePaths<1||
     binding.proposedResourcePaths<1)
    throw Error('A paired review requires changes in both editing areas.');

  // Both builders re-verify their input drafts, source hashes and commit,
  // and independently verify ZIP entries, full compatibility rebuild and
  // rollback. The exact regenerated bytes reject a forged CRC-valid ZIP.
  const expectedPages=await createPagePackage(root,drafts,receipt);
  if(!expectedPages.bytes.equals(pageZip))
    throw Error('Page archive does not match this exact reviewed draft and Git commit.');
  const expectedResources=await createResourcePreview(root,drafts,receipt);
  if(!expectedResources.bytes.equals(resourceZip))
    throw Error('Resource archive does not match this exact reviewed draft and Git commit.');

  const pageManifest=expectedPages.manifest;
  const resourceManifest=expectedResources.manifest;
  if(pageManifest.reviewedGitCommit!==resourceManifest.reviewedGitCommit||
     pageManifest.reviewedGitTree!==resourceManifest.reviewedGitTree||
     pageManifest.reviewReceiptSha256!==resourceManifest.reviewReceiptSha256||
     pageManifest.pageDraftSha256!==resourceManifest.pageDraftSha256||
     pageManifest.resourceDraftSha256!==resourceManifest.resourceDraftSha256||
     pageManifest.reviewedGitCommit!==receipt.reviewedGitCommit||
     pageManifest.reviewReceiptSha256!==receipt.receiptSha256||
     pageManifest.excludedCandidateResourceChanges!==
       resourceManifest.changedFragments.length||
     resourceManifest.excludedTrackedPageEdits!==pageManifest.files.length||
     resourceManifest.previewSourceSha256!==receipt.proposedGeneratedSiteSha256||
     resourceManifest.rollbackVerified!==true||
     pageManifest.partialWebsiteUpdate!==true||
     resourceManifest.partialWebsiteReview!==true)
    throw Error('Paired review manifests do not describe the same complete edit set.');
  if(pageManifest.ownerApproved!==false||
     pageManifest.deployable!==false||
     resourceManifest.ownerApproved!==false||
     resourceManifest.deployable!==false||
     resourceManifest.sourceTreeCommitted!==false)
    throw Error('Review-only archives cannot claim deployment approval.');

  return {
    format:'naxx-matched-private-editor-archives-v1',
    sameReviewedGitCommit:true,
    reviewedGitCommit:receipt.reviewedGitCommit,
    sameReviewReceipt:true,
    reviewReceiptSha256:receipt.receiptSha256,
    exactPageDraft:true,
    exactResourceDraft:true,
    existingPageChanges:pageManifest.files.length,
    proposedResourceChanges:resourceManifest.changedFragments.length,
    pageZipSha256:sha(pageZip),
    resourceZipSha256:sha(resourceZip),
    generatedPreviewSha256:resourceManifest.previewSourceSha256,
    compatibilityReconstructedExactly:true,
    compatibilityRolledBackExactly:true,
    pairCompleteForReview:true,
    finalGitHubPackage:false,
    sourceTreeCommitted:false,
    completeRepositoryBackup:false,
    ownerApproved:false,publishable:false,deployable:false,
    sourceCheckoutModified:false,
    note:'Both archives match one commit-bound receipt. This is an offline review pair, NOT an approved single deployable website update.'
  };
}
function privateFile(root,filename,kind,maxBytes){
  if(typeof filename!=='string'||!path.isAbsolute(filename))
    throw Error('An absolute private '+kind+' file path is required.');
  const parent=fs.realpathSync(path.dirname(filename));
  const checkout=fs.realpathSync(root);
  const rel=path.relative(checkout,parent);
  if(rel===''||(!rel.startsWith('..'+path.sep)&&rel!=='..'&&!path.isAbsolute(rel)))
    throw Error('Private '+kind+' files must be outside the Git repository.');
  const stat=fs.lstatSync(filename);
  if(!stat.isFile()||stat.isSymbolicLink()||
     stat.size<=0||stat.size>maxBytes)
    throw Error('Unsafe or oversized private '+kind+' file.');
  return fs.readFileSync(filename);
}
async function verifySavedPair(root,{pagesFile,resourcesFile,receiptFile,
  pageZipFile,resourceZipFile}={}){
  const items=[pagesFile,resourcesFile,receiptFile,pageZipFile,resourceZipFile];
  if(items.some(x=>typeof x!=='string'||!path.isAbsolute(x))||
     new Set(items.map(x=>path.resolve(x))).size!==5)
    throw Error('Five distinct absolute private file paths are required.');
  const before=items.map((file,index)=>{
    const bytes=privateFile(root,file,index<3?'draft/receipt':'archive',
      index<3?8*1024*1024:75*1024*1024);
    return {bytes,sha256:sha(bytes)};
  });
  const parse=(index)=>{
    const bytes=before[index].bytes;
    if(!Buffer.from(bytes.toString('utf8'),'utf8').equals(bytes))
      throw Error('Private draft or receipt is not valid UTF-8.');
    return JSON.parse(bytes.toString('utf8'));
  };
  const drafts={pages:parse(0),resources:parse(1)};
  const receipt=parse(2);
  const result=await verifyPairedArchives(root,drafts,receipt,before[3].bytes,before[4].bytes);
  // Source files might change during a long 31 MB verification.
  for(let i=0;i<items.length;i++){
    const updated=privateFile(root,items[i],i<3?'draft/receipt':'archive',
      i<3?8*1024*1024:75*1024*1024);
    if(sha(updated)!==before[i].sha256)
      throw Error('A private paired-review input changed during verification.');
  }
  return {...result,privateFilesUnchanged:true};
}
function parseArgs(args){
  const keys=['--pages','--resources','--receipt','--page-zip','--resource-zip'];
  if(!Array.isArray(args)||args.length!==keys.length*2)
    throw Error('Provide --pages, --resources, --receipt, --page-zip and --resource-zip.');
  const result={};
  for(let i=0;i<args.length;i+=2){
    if(!keys.includes(args[i])||Object.hasOwn(result,args[i])||
       typeof args[i+1]!=='string'||!args[i+1])
      throw Error('Unsupported or repeated paired review option.');
    result[args[i]]=args[i+1];
  }
  if(keys.some(key=>!result[key]))
    throw Error('Missing required private paired review input.');
  return {
    pagesFile:result['--pages'],resourcesFile:result['--resources'],
    receiptFile:result['--receipt'],pageZipFile:result['--page-zip'],
    resourceZipFile:result['--resource-zip']
  };
}
if(require.main===module){
  (async()=>{
    const args=parseArgs(process.argv.slice(2));
    return verifySavedPair(path.resolve(__dirname,'..','..'),args);
  })().then(report=>process.stdout.write(JSON.stringify(report,null,2)+'\n'))
    .catch(_=>{
      process.stderr.write('Paired review rejected: private ZIPs, drafts and Git receipt must match the same exact checked-out commit. No private values printed.\n');
      process.exitCode=1;
    });
}
module.exports={verifyPairedArchives,verifySavedPair,parseArgs,privateFile};
